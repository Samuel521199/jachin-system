"""Pluggable graph engine connectors for Memory Growth.

The connector layer consumes the local graph indexes generated by
``graph_sync_adapter``. Markdown Wiki remains the source of truth; connectors
are replaceable sinks for search, temporal reasoning, and external graph
engines.
"""

from __future__ import annotations

import json
import os
import time
import uuid
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol

from .memory_growth import ensure_memory_growth_scaffold, memory_growth_dir


@dataclass(slots=True)
class GraphConnectorResult:
    connector_id: str
    ok: bool
    node_count: int
    edge_count: int
    status: str
    report_path: Path
    warnings: list[str] = field(default_factory=list)
    details: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "connector_id": self.connector_id,
            "ok": self.ok,
            "node_count": self.node_count,
            "edge_count": self.edge_count,
            "status": self.status,
            "report_path": str(self.report_path),
            "warnings": list(self.warnings),
            "details": self.details,
        }


class GraphEngineConnector(Protocol):
    connector_id: str

    def sync(self, nodes: list[dict[str, Any]], edges: list[dict[str, Any]], *, sync_id: str) -> GraphConnectorResult:
        ...


class LocalJsonGraphConnector:
    connector_id = "local_json_graph"

    def sync(self, nodes: list[dict[str, Any]], edges: list[dict[str, Any]], *, sync_id: str) -> GraphConnectorResult:
        root = memory_growth_dir()
        connector_dir = root / "graph" / "connectors" / self.connector_id
        connector_dir.mkdir(parents=True, exist_ok=True)
        snapshot_path = connector_dir / "latest_snapshot.json"
        snapshot = {
            "schema_version": 1,
            "connector_id": self.connector_id,
            "sync_id": sync_id,
            "created_at": _iso_now(),
            "nodes": nodes,
            "edges": edges,
        }
        snapshot_path.write_text(json.dumps(snapshot, ensure_ascii=False, indent=2, default=str) + "\n", encoding="utf-8")
        return _write_connector_report(
            connector_id=self.connector_id,
            sync_id=sync_id,
            ok=True,
            status="synced",
            nodes=nodes,
            edges=edges,
            details={"snapshot_path": str(snapshot_path)},
        )


class CogneeConnector:
    connector_id = "cognee"

    def sync(self, nodes: list[dict[str, Any]], edges: list[dict[str, Any]], *, sync_id: str) -> GraphConnectorResult:
        endpoint = os.getenv("JACHIN_COGNEE_ENDPOINT", "").strip()
        api_key = os.getenv("JACHIN_COGNEE_API_KEY", "").strip()
        if not endpoint:
            return _write_connector_report(
                connector_id=self.connector_id,
                sync_id=sync_id,
                ok=False,
                status="not_configured",
                nodes=nodes,
                edges=edges,
                warnings=["JACHIN_COGNEE_ENDPOINT is not configured"],
                details={"required_env": ["JACHIN_COGNEE_ENDPOINT"], "optional_env": ["JACHIN_COGNEE_API_KEY"], "api_key_present": bool(api_key)},
            )
        return _write_connector_report(
            connector_id=self.connector_id,
            sync_id=sync_id,
            ok=False,
            status="connector_stub_ready",
            nodes=nodes,
            edges=edges,
            warnings=["Cognee transport is not enabled in this build; local graph event contract is ready."],
            details={"endpoint": endpoint, "api_key_present": bool(api_key)},
        )


